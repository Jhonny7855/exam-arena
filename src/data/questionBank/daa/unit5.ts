function randomGraph(rng: Rng, n: number, density: number): Edge[] {
  const edges: Edge[] = []
  for (let u = 0; u < n; u++) {
    for (let v = u + 1; v < n; v++) {
      if (rng() < density) edges.push({ u, v, w: 1 })
    }
  }
  return edges
}

